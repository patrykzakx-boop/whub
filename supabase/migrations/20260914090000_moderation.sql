-- WeldHub moderation: approvals, abuse reports, user blocks and audit history.

alter table public.companies
  add column if not exists moderation_status text not null default 'pending',
  add column if not exists moderation_note text,
  add column if not exists moderated_at timestamptz,
  add column if not exists moderated_by uuid references auth.users(id) on delete set null;

alter table public.companies
  drop constraint if exists companies_moderation_status_check;
alter table public.companies
  add constraint companies_moderation_status_check
  check (moderation_status in ('pending', 'approved', 'rejected'));

-- Existing public profiles have already been visible and remain visible.
update public.companies
set moderation_status = case when status = 'published' then 'approved' else 'pending' end
where moderation_status = 'pending';

alter table public.requests
  add column if not exists moderation_status text not null default 'visible',
  add column if not exists moderation_note text,
  add column if not exists moderated_at timestamptz,
  add column if not exists moderated_by uuid references auth.users(id) on delete set null;

alter table public.requests
  drop constraint if exists requests_moderation_status_check;
alter table public.requests
  add constraint requests_moderation_status_check
  check (moderation_status in ('visible', 'hidden'));

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.blocked_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  reason text not null default 'Naruszenie zasad WeldHub',
  blocked_at timestamptz not null default now(),
  blocked_by uuid references auth.users(id) on delete set null
);

create table if not exists public.moderation_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  target_type text not null check (target_type in ('company', 'request')),
  target_id bigint not null,
  reason text not null check (char_length(reason) between 3 and 80),
  details text check (details is null or char_length(details) <= 2000),
  status text not null default 'open' check (status in ('open', 'resolved', 'dismissed')),
  resolution_note text,
  resolved_at timestamptz,
  resolved_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.moderation_audit_log (
  id bigint generated by default as identity primary key,
  admin_id uuid not null references auth.users(id) on delete restrict,
  action text not null,
  target_type text not null,
  target_id text not null,
  note text,
  created_at timestamptz not null default now()
);

