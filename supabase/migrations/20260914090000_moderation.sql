create or replace function private.queue_company_after_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (select auth.jwt() ->> 'role') = 'service_role' then
    return new;
  end if;

  if tg_op = 'INSERT' then
    new.moderation_status := 'pending';
    new.moderation_note := null;
    new.moderated_at := null;
    new.moderated_by := null;
  elsif row(
    new.name, new.description, new.phone, new.email, new.website, new.logo_url,
    new.address, new.city, new.region, new.services, new.materials,
    new.welding_methods, new.google_place_id
  ) is distinct from row(
    old.name, old.description, old.phone, old.email, old.website, old.logo_url,
    old.address, old.city, old.region, old.services, old.materials,
    old.welding_methods, old.google_place_id
  ) then
    new.moderation_status := 'pending';
    new.moderation_note := null;
    new.moderated_at := null;
    new.moderated_by := null;
  else
    new.moderation_status := old.moderation_status;
    new.moderation_note := old.moderation_note;
    new.moderated_at := old.moderated_at;
    new.moderated_by := old.moderated_by;
  end if;

  return new;
end;
$$;

drop trigger if exists queue_company_after_change on public.companies;
create trigger queue_company_after_change
before insert or update on public.companies
for each row execute function private.queue_company_after_change();
revoke all on function private.queue_company_after_change() from public;

